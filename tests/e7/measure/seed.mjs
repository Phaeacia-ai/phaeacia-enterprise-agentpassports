/* sized: a company whose deletion row total is exactly --rows (C4, C5, C6). */
/* ------------------------------------------------------------------------ */
function sized(label, rows, closed) {
  const tag = `${label}-${rows}`;
  const admin = account(`e7m-${tag}-admin@example.invalid`);
  const companyId = company(`e7m-sized-${tag}`, admin);
  /* Aged, so api.delete_company's export_by precondition is met for a retention_deadline deletion. */
  owner(`insert into app.access_periods (company_id, starts_at, ends_at, export_by, delete_by)
         values (${q(companyId)}, clock_timestamp() - interval '120 days', clock_timestamp() - interval '60 days',
                 clock_timestamp() - interval '46 days', clock_timestamp() - interval '16 days')
         on conflict on constraint access_periods_pkey do update
           set starts_at = excluded.starts_at, ends_at = excluded.ends_at,
               export_by = excluded.export_by, delete_by = excluded.delete_by;`);
  const membership = owner(
    `select id::text from app.memberships where company_id = ${q(companyId)} and user_id = ${q(admin)};`,
  );

  /* The padding is audit rows, which is what tests/db/30-deletion.sh case 25b already pads with: one table,
     one insert, counted by app.export_section_counts and deleted by the one door's fourteenth statement. */
  const already = Number(
    owner(`select coalesce(sum((app.export_section_counts(${q(companyId)}) ->> k)::bigint), 0)
             from unnest(app.deletion_section_names()) k
            where app.export_section_counts(${q(companyId)}) ? k;`),
  );
  const pad = rows - already - 1; /* the company row itself is the one the routine adds */
  if (pad < 0) throw new Error(`sized: the company already holds ${already} rows, above --rows ${rows}`);
  if (pad > 0) {
    owner(`insert into app.audit_events (company_id, actor_user_id, actor_kind, action, entity_type, entity_id, details)
           select ${q(companyId)}, ${q(admin)}, 'member', 'membership.set_roles', 'membership', ${q(membership)},
                  jsonb_build_object('membership_id', ${q(membership)}, 'roles_before', '{member}'::text[],
                                     'roles_after', '{it_reviewer,member}'::text[], 'reason_code', 'measurement_padding')
             from generate_series(1, ${pad});`);
  }
  if (closed) {
    owner(`begin; set local app.tenant_deletion = 'on';
           update app.companies set status = 'suspended' where id = ${q(companyId)};
           update app.companies set status = 'closed' where id = ${q(companyId)}; commit;`);
  }
  const total = Number(
    owner(`select coalesce(sum((app.export_section_counts(${q(companyId)}) ->> k)::bigint), 0) + 1
             from unnest(app.deletion_section_names()) k
            where app.export_section_counts(${q(companyId)}) ? k;`),
  );
  return { fixture: 'sized', label, rows, deletionRows: total, companyId, adminUserId: admin, adminMembershipId: membership, closed };
}

/* ------------------------------------------------------------------------ */
/* case-25a: the oversized company E6 section 9 owed, built by its own helper.*/
/* ------------------------------------------------------------------------ */
function case25a(label) {
  const run = randomUUID().slice(0, 8);
  const admin = account(`e7m-${label}-25a@example.invalid`);
  const companyId = e3lib(
    'source tests/db/e4-lib.sh && source tests/db/e6-lib.sh && source tests/db/e7-lib.sh && ' +
      'E6_RUN="$1" build_oversized_company "$1" "$2"',
    run,
    admin,
  )
    .split('\n')
    .pop()
    .trim();
  if (!/^[0-9a-f-]{36}$/.test(companyId)) throw new Error(`case 25a fixture did not return a company id: ${companyId}`);
  return {
    fixture: 'case-25a',
    label,
    companyId,
    adminUserId: admin,
    adminMembershipId: owner(`select id::text from app.memberships where company_id = ${q(companyId)} and user_id = ${q(admin)};`),
    sectionCounts: JSON.parse(owner(`select app.export_section_counts(${q(companyId)})::text;`)),
  };
}

const args = parseArgs(process.argv.slice(2));
const out =
  args.fixture === 'plan-figure'
    ? planFigure(args.label)
    : args.fixture === 'sized'
      ? sized(args.label, args.rows, args.closed)
      : case25a(args.label);
process.stdout.write(`${JSON.stringify(out)}\n`);
