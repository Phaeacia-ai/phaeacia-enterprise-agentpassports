#!/usr/bin/env node
/* The fixtures section 6's measurements need, built OWNER-SIDE and deterministically.
 *
 *   node tests/e7/measure/seed.mjs plan-figure --label <label>
 *   node tests/e7/measure/seed.mjs sized --rows <n> --label <label> [--closed]
 *   node tests/e7/measure/seed.mjs case-25a --label <label>
 *
 * It prints one JSON object of ids on stdout, which the measurement scripts read.
 *
 * WHY OWNER-SIDE, SAID PLAINLY. No product route writes a candidate at the content bound, and none
 * writes three hundred releases in a minute. Design section 5 already labels this kind of fixture
 * owner-side, and tests/db/e6-lib.sh's pad_candidate does exactly it for case 25a. What is built
 * here is a fixture of the right SHAPE and the right BYTES: the row counts of design section 6's
 * plan figures, with candidate content at 262,144 bytes and assembled release content near 393,216.
 *
 * WHAT THAT COSTS, WRITTEN DOWN SO NO READER OVERSTATES THE MEASUREMENT. The envelope and release
 * identity triggers are disabled for the bulk insert and the derived columns are computed here, so
 * the releases are NOT proof that the product's assembly rules hold at this size; E4 to E6 prove
 * those, one release at a time. The candidate trigger stays ENABLED, so every candidate row is one
 * the product's own identity rule accepted. What the measurements below then measure is the export
 * script's streaming, the deletion's duration and the lock's hold time over rows of the right size
 * and number, which is what section 6 asks for and all it asks for.
 *
 * DETERMINISM. --label decides every generated byte: content is repeat(md5(label || key), n), so the
 * same label on the same seed reproduces the same fixture, and the label is what each measurement
 * record carries as its seed.
 */
import { randomUUID } from 'node:crypto';

import { libsh } from '../../e2/helpers/stack.mjs';
import { e3lib } from '../../e3/stack/helpers.mjs';
import { owner, ownerValue } from './helpers.mjs';

const LABEL_RE = /^[a-z0-9][a-z0-9-]{0,30}$/;

function parseArgs(argv) {
  const a = { fixture: argv[0], label: null, rows: null, closed: false };
  for (let i = 1; i < argv.length; i++) {
    if (argv[i] === '--label') a.label = argv[++i];
    else if (argv[i] === '--rows') a.rows = Number.parseInt(argv[++i], 10);
    else if (argv[i] === '--closed') a.closed = true;
    else {
      process.stderr.write(`seed: unknown argument ${argv[i]}\n`);
      process.exit(2);
    }
  }
  if (!['plan-figure', 'sized', 'case-25a'].includes(a.fixture)) {
    process.stderr.write('usage: node tests/e7/measure/seed.mjs plan-figure|sized|case-25a --label LABEL [--rows N] [--closed]\n');
    process.exit(2);
  }
  if (a.label === null || !LABEL_RE.test(a.label)) {
    process.stderr.write('seed: --label matches ^[a-z0-9][a-z0-9-]{0,30}$ and decides every generated byte\n');
    process.exit(2);
  }
  if (a.fixture === 'sized' && !(Number.isInteger(a.rows) && a.rows >= 100)) {
    process.stderr.write('seed: sized needs --rows N, an integer of at least 100\n');
    process.exit(2);
  }
  return a;
}

/** A confirmed synthetic account through GoTrue's admin API, as every other fixture makes one.
 *  Idempotent on purpose: tests/db/00-seed.sh resets schema `app` and leaves `auth.users` alone, so a second run
 *  with the same --label meets an account that already exists. Re-using it keeps the label's determinism, which
 *  is the whole point of the label; inventing a new address per run would not. */
function account(email) {
  try {
    return libsh('create_user', email, 'synthetic-password-1');
  } catch (e) {
    if (!String(e.message).includes('email_exists')) throw e;
    const id = owner(`select id::text from auth.users where email = ${q(email)};`);
    if (!/^[0-9a-f-]{36}$/.test(id)) throw e;
    return id;
  }
}

/** A company through the product's own provisioning route, with the seeded operator. */
function company(slug, adminUser) {
  const id = e3lib('company "$1" "$2"', slug, adminUser);
  if (!/^[0-9a-f-]{36}$/.test(id)) throw new Error(`provisioning did not return a company id: ${id.slice(0, 200)}`);
  return id;
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

/** The shared rows every envelope and release points at, taken from the seed rather than invented. */
function sharedRefs() {
  const row = owner(
    `select it.gate_id::text, it.target, (select id::text from app.release_policies order by id limit 1),
            (select id::text from app.gate_identities order by id limit 1)
       from app.installer_texts it order by it.gate_id, it.target limit 1;`,
  );
  const [gateId, target, policyId, anyGate] = row.split('|');
  if (!gateId || !target || !policyId) throw new Error('the seed holds no installer text, target or policy to point at');
  return { gateId, target, policyId, anyGate };
}

/* ------------------------------------------------------------------------ */
/* plan-figure: design section 6 C1's second company, at the plan's figures.  */
/* ------------------------------------------------------------------------ */
function planFigure(label) {
  const admin = account(`e7m-${label}-admin@example.invalid`);
  const companyId = company(`e7m-plan-${label}`, admin);
  owner(`insert into app.access_periods (company_id, starts_at, ends_at, export_by, delete_by)
         values (${q(companyId)}, clock_timestamp() - interval '1 day', clock_timestamp() + interval '30 days',
                 clock_timestamp() + interval '44 days', clock_timestamp() + interval '74 days')
         on conflict on constraint access_periods_pkey do update
           set ends_at = excluded.ends_at, export_by = excluded.export_by, delete_by = excluded.delete_by;`);
  const adminMembership = owner(
    `select id::text from app.memberships where company_id = ${q(companyId)} and user_id = ${q(admin)};`,
  );
  const { gateId, target, policyId } = sharedRefs();

  /* 25 active and 25 removed memberships beside the first administrator (section 6 C1). The accounts are
     inserted owner-side: fifty admin-API calls would be fifty HTTP round trips for rows nothing signs in with. */
  owner(`do $$
declare u uuid; i int;
begin
  for i in 1..50 loop
    u := gen_random_uuid();
    insert into auth.users (id, instance_id, aud, role, email, email_confirmed_at, created_at, updated_at)
    values (u, '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated',
            format('e7m-%s-m%s@example.invalid', ${q(label)}, i), clock_timestamp(), clock_timestamp(), clock_timestamp());
    insert into app.memberships (company_id, user_id, status, roles, removed_at)
    values (${q(companyId)}, u,
            case when i <= 25 then 'active' else 'removed' end, '{member}',
            case when i <= 25 then null else clock_timestamp() end);
  end loop;
end $$;`);

  /* 50 agents, ten candidate versions each at the content bound. The candidate identity trigger stays ON. */
  owner(`do $$
declare a uuid; i int; j int; body text; derived text;
begin
  for i in 1..50 loop
    insert into app.agents (company_id, name, creator_membership_id, owner_membership_id)
    values (${q(companyId)}, format('e7m-agent-%s', i), ${q(adminMembership)}, ${q(adminMembership)})
    returning id into a;
    for j in 1..10 loop
      -- 262,144 bytes exactly: the placeholder the content CHECK requires, then deterministic hex padding.
      body := '<!-- installer core and branches inserted on upload -->';
      body := body || repeat(md5(${q(label)} || '-' || i::text || '-' || j::text), (262144 - octet_length(body)) / 32);
      body := body || repeat('x', 262144 - octet_length(body));
      derived := jsonb_build_object(
        'validated_at', to_char(clock_timestamp() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
        'agent', format('e7m-agent-%s', i), 'sequence', j)::text;
      insert into app.candidate_versions
        (company_id, agent_id, sequence, state, version, author_membership_id, content, content_sha256,
         derived_canonical, derived_sha256, gate_id, validated_at, attested_by)
      values (${q(companyId)}, a, j, 'draft', 1, ${q(adminMembership)}, body, '\\x00'::bytea,
              derived, '\\x00'::bytea, ${q(gateId)}, clock_timestamp(), ${q(adminMembership)});
    end loop;
  end loop;
end $$;`);

  /* One audience group, so every envelope's audience_group_ids points at a real group of this company. */
  const groupId = ownerValue(
    `insert into app.groups (company_id, name, created_by_membership_id)
       values (${q(companyId)}, 'e7m-audience', ${q(adminMembership)}) returning id::text;`,
  );
  if (!/^[0-9a-f-]{36}$/.test(groupId)) throw new Error(`the audience group's id did not come back: ${groupId}`);

  /* 300 releases with assembled content near 393,216 bytes, each with its own envelope. The two IDENTITY
     triggers are disabled for the bulk insert and the derived columns are computed here; the header says why.
     The IMMUTABILITY trigger stays ENABLED, and the supersession of each agent's earlier releases is done by
     the update it already admits (published -> published with the two superseded columns set together), because
     `releases_one_current` allows exactly one current release per agent and target. */
  owner(`do $$
declare v record; e uuid; r uuid; prev uuid; prev_agent uuid; n int := 0; assembled text; canon text;
begin
  alter table app.review_envelopes disable trigger review_envelopes_2_identity;
  alter table app.releases disable trigger releases_2_identity;
  for v in select id, agent_id, sequence from app.candidate_versions
            where company_id = ${q(companyId)} order by agent_id, sequence limit 300 loop
    n := n + 1;
    if prev_agent is distinct from v.agent_id then prev := null; prev_agent := v.agent_id; end if;
    assembled := repeat(md5(${q(label)} || '-rel-' || n::text), 393216 / 32);
    canon := jsonb_build_object('release', n, 'label', ${q(label)})::text;
    insert into app.review_envelopes
      (company_id, agent_id, candidate_id, revision, content_sha256, derived_sha256, gate_id,
       gate_identity_sha256, target, installer_text_sha256, core_sha256, branch_sha256, judge_sha256,
       policy_id, policy_sha256, assembled_bytes, audience_group_ids, envelope_canonical, envelope_sha256,
       created_by_membership_id)
    values (${q(companyId)}, v.agent_id, v.id, 1,
            sha256(convert_to('c' || n::text, 'UTF8')), sha256(convert_to('d' || n::text, 'UTF8')), ${q(gateId)},
            sha256(convert_to('g' || n::text, 'UTF8')), ${q(target)}, sha256(convert_to('i' || n::text, 'UTF8')),
            sha256(convert_to('k' || n::text, 'UTF8')), sha256(convert_to('b' || n::text, 'UTF8')),
            sha256(convert_to('j' || n::text, 'UTF8')), ${q(policyId)}, sha256(convert_to('p' || n::text, 'UTF8')),
            octet_length(assembled), array[${q(groupId)}::uuid], canon, sha256(convert_to(canon, 'UTF8')),
            ${q(adminMembership)})
    returning id into e;
    -- The previous release of this agent is superseded FIRST, with the id the next one is about to take:
    -- releases_one_current refuses a second current release for (agent_id, target), and the
    -- superseded_by_release_id foreign key is DEFERRABLE INITIALLY DEFERRED, so it is checked at commit,
    -- by which time the row it points at exists. The transition itself is the one app.release_immutable
    -- admits, which is why that trigger is not disabled.
    r := gen_random_uuid();
    if prev is not null then
      update app.releases set superseded_by_release_id = r, superseded_at = clock_timestamp() where id = prev;
    end if;
    insert into app.releases
      (id, company_id, agent_id, candidate_id, envelope_id, target, gate_id, content_sha256, derived_sha256,
       installer_text_sha256, core_sha256, branch_sha256, judge_sha256, policy_id, policy_sha256,
       audience_group_ids, envelope_sha256, assembled_content, assembled_sha256, assembled_bytes,
       published_by_membership_id)
    values (r, ${q(companyId)}, v.agent_id, v.id, e, ${q(target)}, ${q(gateId)},
            sha256(convert_to('c' || n::text, 'UTF8')), sha256(convert_to('d' || n::text, 'UTF8')),
            sha256(convert_to('i' || n::text, 'UTF8')), sha256(convert_to('k' || n::text, 'UTF8')),
            sha256(convert_to('b' || n::text, 'UTF8')), sha256(convert_to('j' || n::text, 'UTF8')),
            ${q(policyId)}, sha256(convert_to('p' || n::text, 'UTF8')), array[${q(groupId)}::uuid],
            sha256(convert_to(canon, 'UTF8')), assembled, sha256(convert_to(assembled, 'UTF8')),
            octet_length(assembled), ${q(adminMembership)});
    prev := r;
  end loop;
  -- The deferred superseded_by_release_id checks are still queued, and ALTER TABLE refuses a table with
  -- pending trigger events, so they are run here rather than at commit.
  set constraints all immediate;
  alter table app.releases enable trigger releases_2_identity;
  alter table app.review_envelopes enable trigger review_envelopes_2_identity;
end $$;`);

  /* A 10,000-row download ledger (section 6 C1; E4's own read ceiling is the same number). */
  owner(`insert into app.release_downloads (company_id, release_id, membership_id, authorized_at)
         select ${q(companyId)}, r.id, m.id, clock_timestamp() - (g || ' seconds')::interval
           from generate_series(1, 10000) g
           join lateral (select id from app.releases where company_id = ${q(companyId)}
                          order by id offset (g % 300) limit 1) r on true
           join lateral (select id from app.memberships where company_id = ${q(companyId)} and status = 'active'
                          order by id offset (g % 25) limit 1) m on true;`);

  const counts = owner(`select app.export_section_counts(${q(companyId)})::text;`);
  const bytes = owner(
    `select app.company_content_bytes(${q(companyId)}) || '|' || app.company_assembled_bytes(${q(companyId)});`,
  );
  const [contentBytes, assembledBytes] = bytes.split('|');
  return {
    fixture: 'plan-figure',
    label,
    companyId,
    adminUserId: admin,
    adminMembershipId: adminMembership,
    groupId,
    sectionCounts: JSON.parse(counts),
    contentBytes: Number(contentBytes),
    assembledBytes: Number(assembledBytes),
  };
}

