#!/usr/bin/env node
/* The capacity envelope's world, built OWNER-SIDE and deterministically, for the E8 day-4 load run
 * (docs/e8/design.md section 4; the plan's readiness item 6: "ten companies, 25 users/company, 20
 * concurrent active sessions; 50 agents/company, ten retained versions/agent, 256 KiB/version").
 *
 *   node tests/e8/load/seed.mjs --label <label> [--companies 10] [--no-reseed]
 *
 * It prints one JSON object on stdout and writes the same object to
 * .scratch/e8/load/world-<label>.json, which mix.mjs and plans.mjs read. The data is NOT committed;
 * this file and the record are (tests/e7/measure/README.md's pattern, which this directory follows).
 *
 * WHAT IS NOT A GATE. Nothing here asserts a target. scripts/check.sh does not run this directory.
 * A measurement that asserted a bound would turn a number into a promise.
 *
 * WHY OWNER-SIDE. No product route writes five thousand candidates at the content bound in a run of
 * a few minutes, and none writes a thousand releases. The shape and the bytes are the envelope's;
 * the identity triggers that can stay on, stay on. What that buys and what it costs:
 *   - app.candidate_versions: the IDENTITY trigger is ENABLED for every one of the 5,000 rows, so
 *     each row is one the product's own content rule accepted (the placeholder, the byte bounds,
 *     the control-character and CR refusals, the derived record's shape and its five-minute clock).
 *   - app.review_envelopes and app.releases: their identity triggers are ENABLED too, so each
 *     release's assembled bytes are the product's own assembly of the candidate's content and the
 *     registered installer text (006:3197). This seed therefore does NOT need E7's disabled-trigger
 *     caveat for releases.
 *   - What is still NOT proven by this seed: that the product's ROUTES would have produced this
 *     world one call at a time. E3 to E6 prove that; this builds the rows to measure reads over.
 *
 * THE CONTENT IS PROSE AND NOT HEXADECIMAL (E7G-F13, evidence/e7-docs.md:81). E7's C1 fixture padded
 * its content with md5 hex, which JSON escapes not at all, and its escaping measurement was worth
 * nothing as a result. The body here is the committed SYNTHETIC passport padded with an English
 * prose line to exactly 262,144 bytes, through tests/e3/stack/helpers.mjs largePassport(), which is
 * the same fixture E4's capacity sample and E3's case 20 use.
 *
 * DETERMINISM, AND WHAT THE LABEL DECIDES. --label decides every generated IDENTITY (the account
 * addresses, the company slugs, the agent and group names) and the twelve-character marker that
 * makes each candidate's body distinct. It does not decide the body itself, which is the committed
 * fixture: a label that decided all 262,144 bytes would have to generate them, and generated bytes
 * are how E7G-F13 happened. The same label on the same seed reproduces the same world.
 *
 * THE STACK. This reseeds through bash tests/db/00-seed.sh and nothing else. It never calls
 * `supabase stop`, `start` or `db reset`, and it must not run beside another stack suite.
 */
