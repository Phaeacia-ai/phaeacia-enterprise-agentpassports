/** The owner connection, as an operator's own command would be. Never printed. */
function sqlScript(text, { timeoutMs = 1_800_000 } = {}) {
  const { dbContainer } = stackEnv();
  const r = spawnSync(
    'docker',
    ['exec', '-i', dbContainer, 'psql', '-U', 'postgres', '-X', '-v', 'ON_ERROR_STOP=1', '-At'],
    { input: text, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, timeout: timeoutMs },
  );
  if (r.status !== 0) throw new Error(`owner psql exited ${r.status}: ${`${r.stderr}${r.stdout}`.slice(0, 900)}`);
  return (r.stdout ?? '').trim();
}
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const dollar = (tag, s) => {
  const t = `$${tag}$`;
  if (s.includes(t)) throw new Error(`the dollar tag ${tag} occurs in the text`);
  return `${t}${s}${t}`;
};
/* psql under -At prints a data-modifying statement's command tag ("INSERT 0 1") AFTER its RETURNING
   row, so a read that expects one value drops the tags and takes the first line that is left. E7's
   measurement helper carries the same regex for the same reason. */
const TAG =
  /^(INSERT|UPDATE|DELETE|MERGE|COPY|CREATE|ALTER|DROP|TRUNCATE|BEGIN|COMMIT|ROLLBACK|SET|DO|NOTIFY|GRANT|REVOKE|ANALYZE|VACUUM|SELECT [0-9]+$)\b/;
const one = (text) => {
  const lines = sqlScript(text)
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l.length > 0 && !TAG.test(l));
  return lines[0] ?? '';
};

/** One tests/db/e3-lib.sh call. The seeded password stays in bash and never enters this file. */
function e3lib(script, ...args) {
  const r = spawnSync(
    'bash',
    [
      '-c',
      `cd "$0" && source tests/db/lib.sh && source .scratch/e2/ids.env && source tests/db/e3-lib.sh && ${script}`,
      ROOT,
      ...args,
    ],
    { encoding: 'utf8', env: process.env },
  );
  if (r.status !== 0) throw new Error(`e3-lib failed (exit ${r.status}): ${r.stderr.slice(0, 400)}`);
  return r.stdout.trim();
}

/** A confirmed synthetic account. Idempotent, as E7's measurement seed is: 00-seed.sh resets schema
    app and leaves auth.users alone, so a second run with the same label meets accounts that exist. */
function account(email) {
  const existing = one(`select coalesce((select id::text from auth.users where email = ${q(email)}), '');`);
  if (UUID_RE.test(existing)) return existing;
  const id = e3lib('create_user "$1" "$PW"', email);
  if (!UUID_RE.test(id)) throw new Error(`the account ${email} was not created`);
  return id;
}

/* ---------------------------------------------------------------- the content template */

/* The padding's vocabulary. WHY A WORD LIST AND NOT A REPEATED LINE. E4's largePassport() pads with
   one sentence repeated, which is the right fixture for a route test and the wrong one for a
   capacity measurement: 128 MB of one repeated line is 6 MB after TOAST compression, so the storage,
   the page reads and the detoast cost of the measured download would all be a twentieth of a real
   tenant's. These sentences are assembled from a fixed vocabulary by a deterministic generator
   seeded from --label, which is prose a person could read, compresses about as English prose does,
   and carries the quotes and the non-ASCII letters E7G-F13 says a real tenant's content carries and
   this project's earlier fixture did not. It is NOT hexadecimal, which is the whole of that
   lesson. */
const WORDS = Object.freeze(
  ('the a an and or but when while after before each every any some this that these those record records row rows ' +
    'column columns table list order sorted first last next previous entry entries field fields value values name ' +
    'names label labels date dates time times note notes summary summaries detail details step steps run runs ' +
    'result results report reports check checks rule rules limit limits reason reasons change changes review ' +
    'reviews release releases version versions agent agents company companies member members group groups owner ' +
    'owners reader readers writer writers request requests answer answers page pages line lines block blocks file ' +
    'files folder folders copy copies draft drafts state states status statuses it is was are were has have had ' +
    'will would can could should must may might keeps keep kept reads read writes write wrote takes take took ' +
    'gives give gave shows show showed asks ask asked tells tell told finds find found leaves leave left holds ' +
    'hold held moves move moved sets set puts put opens open closed begins begin began ends end ended plainly ' +
    'clearly simply exactly carefully quietly often rarely always never sometimes usually rather than instead of ' +
    'without within between across through against beside around below above under over into onto from with for ' +
    'about ueber naiv koennen muessen resume cafe role fidele piece').split(' '),
);
const ACCENTS = Object.freeze(['ü', 'ö', 'ä', 'é', 'è', 'ç', 'à', 'ñ']);

/** A deterministic stream of numbers in [0, 1) from a string seed: FNV-1a into xorshift32. */
function rng(seedText) {
  let h = 2166136261;
  for (let i = 0; i < seedText.length; i++) {
    h ^= seedText.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  h |= 0;
  return () => {
    h ^= h << 13;
    h ^= h >>> 17;
    h ^= h << 5;
    h |= 0;
    return (h >>> 0) / 4294967296;
  };
}

/** `bytes` bytes of deterministic prose: sentences of eight to sixteen words, wrapped near eighty
    columns, with a quoted phrase and an accented word now and then. No control characters, no
    carriage return, no Markdown heading and no fence, which is what the gate and the content CHECK
    refuse (003:119-131). */
function prosePadding(seedText, bytes) {
  const next = rng(seedText);
  const pick = (list) => list[Math.floor(next() * list.length)];
  const out = [];
  let size = 0;
  let line = '';
  while (size < bytes) {
    const words = [];
    const n = 8 + Math.floor(next() * 9);
    for (let i = 0; i < n; i++) {
      let w = pick(WORDS);
      if (next() < 0.02) w = w + pick(ACCENTS);
      words.push(w);
    }
    if (next() < 0.08) words.splice(Math.floor(next() * words.length), 0, `"${pick(WORDS)} ${pick(WORDS)}"`);
    let sentence = `${words.join(' ')}.`;
    sentence = sentence.charAt(0).toUpperCase() + sentence.slice(1);
    for (const word of sentence.split(' ')) {
      if (line.length + word.length + 1 > 78) {
        out.push(line);
        size += Buffer.byteLength(line, 'utf8') + 1;
        line = '';
      }
      line = line.length === 0 ? word : `${line} ${word}`;
    }
  }
  out.push(line);
  return `${out.join('\n')}\n`;
}

/** The 262,144-byte prose body, with a twelve-character marker where the revision goes, and the
    derived record the gate stamps for it. The gate must accept the body unchanged, or the seed is
    not building rows the product's own rule accepts. */
async function template(label) {
  const base = largePassport(MARKER).toString('utf8').replace(/ +$/, '');
  /* largePassport() pads with one repeated line and then with trailing spaces; both are replaced
     here by generated prose, and the result is trimmed to the content bound byte for byte. */
  const at = base.indexOf('## 4.');
  if (at < 0) throw new Error('the fixture has no section 4 to pad before');
  const head = base.slice(0, base.indexOf('The sorter keeps every record'));
  const tail = base.slice(at);
  const room = ENVELOPE.contentBytes - Buffer.byteLength(head, 'utf8') - Buffer.byteLength(tail, 'utf8') - 2;
  let body = `${head}${prosePadding(`${label}-padding`, room)}\n${tail}`;
  while (Buffer.byteLength(body, 'utf8') > ENVELOPE.contentBytes) body = body.slice(0, -1);
  body += ' '.repeat(ENVELOPE.contentBytes - Buffer.byteLength(body, 'utf8'));
  if (Buffer.byteLength(body, 'utf8') !== ENVELOPE.contentBytes)
    throw new Error(`the template is ${Buffer.byteLength(body, 'utf8')} bytes, not ${ENVELOPE.contentBytes}`);
  if (!body.includes(`${PROSE} Revision ${MARKER}.`)) throw new Error('the template carries no marker');
  const { gate } = await import('../../../lib/passport/gate.mjs');
  const verdict = gate(Buffer.from(body, 'utf8'), 'text/markdown', { validatedAt: new Date().toISOString() });
  if (!verdict.ok)
    throw new Error(`the gate refuses the template: ${verdict.code} ${JSON.stringify(verdict.problems ?? []).slice(0, 300)}`);
  if (verdict.text !== body) throw new Error('the gate does not accept the template unchanged');
  return { body, derivedCanonical: verdict.derivedCanonical };
}

/** The derived record as SQL, with validated_at restamped at insert so the trigger's five-minute
    freshness test meets a fresh attestation however long the seed has been running.
    THE LIMIT, STATED: this is the TEMPLATE's derived record, and each row's body differs from the
    template by its twelve-character marker, so a row's derived record is not a re-derivation of that
    row's own bytes. The trigger does not compare the two (003:225-270 reads the derived record's
    shape and its clock and nothing else), and nothing this run measures replays it: replayStored()
    is on the review path, which is not one of the mix's five classes. E4's capacity sample makes the
    same trade in the same words (tests/e4/stack/capacity.test.mjs derivedOf). */
function derivedExpr(derivedCanonical) {
  const stamp = /"validated_at":"[^"]+"/.exec(derivedCanonical)?.[0];
  if (!stamp) throw new Error('the derived record carries no validated_at');
  return `replace(${dollar('d', derivedCanonical)}, ${q(stamp)},
            '"validated_at":"' || to_char(clock_timestamp() at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') || '"')`;
}

/* ---------------------------------------------------------------- one company */

/* The per-agent version shape, ten retained versions (the envelope's number), chosen so that one
   company holds every row the mix's five classes read:
     1 to 5  superseded  history; version 5 carried the release that version 6's supersedes
     6       approved    the CURRENT release of the agent, the catalog's "available" row
     7       approved    an approved candidate with no release
     8       changes_requested
     9       submitted   with SHAPE.queueEnvelopes envelopes and SHAPE.queueReviews reviews:
                         E4's worst review-queue page (50 of them per company), which is the row
                         E6SC-F1 measured at 2,122.4 and 2,159.0 ms and design 4.3 says is in this mix
    10       draft
   Releases per agent: two, version 5's (superseded) and version 6's (current). */
const SUPERSEDED = [1, 2, 3, 4, 5];
const OLD_RELEASE_SEQ = 5;
const CURRENT_RELEASE_SEQ = 6;
const APPROVED_NO_RELEASE_SEQ = 7;
const CHANGES_SEQ = 8;
const SUBMITTED_SEQ = 9;
const DRAFT_SEQ = 10;

function companyWorld(label, index, tpl) {
  const slug = `e8l-${label}-c${index}`;
  const adminUser = account(`${slug}-admin@example.invalid`);
  const reviewerUser = account(`${slug}-reviewer@example.invalid`);
  const authorUser = account(`${slug}-author@example.invalid`);
  const companyId = e3lib('company "$1" "$2"', slug, adminUser);
  if (!UUID_RE.test(companyId)) throw new Error(`company ${slug} was not provisioned: ${companyId.slice(0, 200)}`);

  const adminMembership = one(
    `select id::text from app.memberships where company_id = ${q(companyId)} and user_id = ${q(adminUser)};`,
  );
  /* The admin is also the IT reviewer, because the envelope gives one company twenty concurrent
     sessions over two identities and design 4.1 asks five caller shapes of them. Recorded as a
     deviation in docs/e8/design.md's day-4 amendment block. */
  const reviewerMembership = one(
    `update app.memberships set roles = '{company_admin,it_reviewer,member}'
       where id = ${q(adminMembership)};
     insert into app.memberships (company_id, user_id, roles)
       values (${q(companyId)}, ${q(reviewerUser)}, '{business_reviewer,member}') returning id::text;`,
  );
  const authorMembership = one(
    `insert into app.memberships (company_id, user_id, roles)
       values (${q(companyId)}, ${q(authorUser)}, '{member}') returning id::text;`,
  );
  const fillers = ENVELOPE.usersPerCompany - 3;

  /* The remaining members: rows, not sessions. Fifty admin-API calls would be fifty round trips for
     accounts nobody signs in with, which is the trade E7's measurement seed makes in the same place. */
  sqlScript(`do $$
declare u uuid; i int;
begin
  for i in 1..${fillers} loop
    u := gen_random_uuid();
    insert into auth.users (id, instance_id, aud, role, email, email_confirmed_at, created_at, updated_at)
    values (u, '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated',
            format('%s-m%s@example.invalid', ${q(slug)}, i), clock_timestamp(), clock_timestamp(), clock_timestamp());
    insert into app.memberships (company_id, user_id, roles) values (${q(companyId)}, u, '{member}');
  end loop;
end $$;`);

  /* Ten groups. The admin is in all ten; the business reviewer is in group 1 alone, so the catalog's
     two caller shapes differ by what they may see; every other member is in group 0. */
  sqlScript(`
insert into app.groups (company_id, name, created_by_membership_id)
  select ${q(companyId)}, format('%s-group-%s', ${q(slug)}, g), ${q(adminMembership)}
    from generate_series(0, ${SHAPE.groupsPerCompany - 1}) g;
insert into app.group_members (group_id, company_id, membership_id, added_by_membership_id)
  select gr.id, gr.company_id, ${q(adminMembership)}, ${q(adminMembership)}
    from app.groups gr where gr.company_id = ${q(companyId)};
insert into app.group_members (group_id, company_id, membership_id, added_by_membership_id)
  select gr.id, gr.company_id, ${q(reviewerMembership)}, ${q(adminMembership)}
    from app.groups gr where gr.company_id = ${q(companyId)} and gr.name = format('%s-group-1', ${q(slug)});
insert into app.group_members (group_id, company_id, membership_id, added_by_membership_id)
  select gr.id, gr.company_id, m.id, ${q(adminMembership)}
    from app.groups gr join app.memberships m on m.company_id = gr.company_id and m.status = 'active'
   where gr.company_id = ${q(companyId)} and gr.name = format('%s-group-0', ${q(slug)})
     and m.id <> ${q(adminMembership)};`);

  /* 50 agents, ten versions each at the content bound. The token is twelve characters, so every body
     is exactly ${ENVELOPE.contentBytes} bytes however the label and the indices fall. */
  const token = `substr(${q(`${label}zzzzz`)}, 1, 5) || lpad(${index}::text, 2, '0') || lpad(a.agent_no::text, 3, '0') || lpad(s::text, 2, '0')`;
  sqlScript(`
insert into app.agents (company_id, name, creator_membership_id, owner_membership_id)
  select ${q(companyId)}, format('%s-agent-%s', ${q(slug)}, g), ${q(authorMembership)}, ${q(authorMembership)}
    from generate_series(1, ${ENVELOPE.agentsPerCompany}) g;
create temp table seed_agents as
  select id as agent_id, company_id, substring(name from '[0-9]+$')::int as agent_no
    from app.agents where company_id = ${q(companyId)};
with tpl as (select ${dollar('c', tpl.body)} as body)
insert into app.candidate_versions
  (company_id, agent_id, sequence, author_membership_id, content, content_sha256,
   derived_canonical, derived_sha256, gate_id, validated_at, attested_by)
select a.company_id, a.agent_id, s, ${q(authorMembership)},
       replace(tpl.body, ${q(MARKER)}, ${token}),
       '\\x00'::bytea, ${derivedExpr(tpl.derivedCanonical)}, '\\x00'::bytea,
       (select id from app.gate_identities where active), clock_timestamp(), ${q(authorMembership)}
  from tpl, seed_agents a, generate_series(1, ${ENVELOPE.versionsPerAgent}) s;
-- Every row is inserted as a DRAFT and then walked through app.candidate_immutable's own state
-- machine (003:274-306), one transition at a time, so no state in this world is one the product
-- would refuse to reach. The contributor rows go in first, because app.contributors_frozen()
-- refuses them once a candidate has left the draft state, which is the rule and not an obstacle.
insert into app.candidate_contributors (candidate_id, membership_id, kind, observed)
  select v.id, v.author_membership_id, k, true
    from app.candidate_versions v join seed_agents a using (agent_id), (values ('author'), ('submitter')) x(k)
   where v.sequence <> ${DRAFT_SEQ};
update app.candidate_versions v set state = 'submitted', submitted_at = clock_timestamp(),
       submitted_by_membership_id = v.author_membership_id
  from seed_agents a where v.agent_id = a.agent_id and v.sequence <= ${SUBMITTED_SEQ};
update app.candidate_versions v set state = 'approved'
  from seed_agents a where v.agent_id = a.agent_id and v.sequence <= ${APPROVED_NO_RELEASE_SEQ};
update app.candidate_versions v set state = 'changes_requested'
  from seed_agents a where v.agent_id = a.agent_id and v.sequence = ${CHANGES_SEQ};
update app.candidate_versions v set state = 'superseded'
  from seed_agents a where v.agent_id = a.agent_id and v.sequence <= ${SUPERSEDED.at(-1)};
select 'CANDIDATES|' || (select count(*) from app.candidate_versions where company_id = ${q(companyId)})
    || '|' || (select octet_length(content) from app.candidate_versions
                where company_id = ${q(companyId)} order by id limit 1);`);

  /* The releases: version 5's, superseded by version 6's. Both at ${SHAPE.downloadTarget}, the
     largest registered installer text, so each assembly is the largest the product can make at the
     content bound. The envelope and release identity triggers stay ENABLED. Even agents address all
     ten groups and odd agents group 0 alone (E5's shape), so the two catalog callers differ. */
  sqlScript(`
create temp table seed_agents as
  select id as agent_id, company_id, substring(name from '[0-9]+$')::int as agent_no
    from app.agents where company_id = ${q(companyId)};
create temp table seed_audience as
  select a.agent_id,
         case when a.agent_no % 2 = 0
              then (select array_agg(gr.id order by gr.id::text collate "C") from app.groups gr where gr.company_id = ${q(companyId)})
              else array[(select gr.id from app.groups gr where gr.company_id = ${q(companyId)}
                           and gr.name = format('%s-group-0', ${q(slug)}))] end as group_ids
    from seed_agents a;
insert into app.review_envelopes
  (company_id, agent_id, candidate_id, revision, content_sha256, derived_sha256, gate_id,
   gate_identity_sha256, target, installer_text_sha256, core_sha256, branch_sha256, judge_sha256,
   policy_id, policy_sha256, assembled_bytes, audience_group_ids, envelope_canonical, envelope_sha256,
   created_by_membership_id)
select v.company_id, v.agent_id, v.id, 1, v.content_sha256, v.derived_sha256, i.gate_id,
       g.identity_sha256, i.target, i.text_sha256, i.core_sha256, i.branch_sha256, i.judge_sha256,
       p.id, p.sha256, app.assembled_bytes(v.content, i.text), au.group_ids,
       'e8-load-release-' || v.id::text, sha256(convert_to('e8-load-release-' || v.id::text, 'UTF8')),
       ${q(authorMembership)}
  from app.candidate_versions v
  join seed_agents a using (agent_id)
  join seed_audience au on au.agent_id = v.agent_id
  join app.gate_identities g on g.active
  join app.installer_texts i on i.gate_id = g.id and i.target = ${q(SHAPE.downloadTarget)}
  cross join app.release_policies p
 where v.company_id = ${q(companyId)} and p.active
   and v.sequence in (${OLD_RELEASE_SEQ}, ${CURRENT_RELEASE_SEQ});
insert into app.reviews (company_id, candidate_id, envelope_id, role, decision, reviewer_membership_id, reason)
  select e.company_id, e.candidate_id, e.id, r.role, 'approved',
         case r.role when 'it' then ${q(adminMembership)}::uuid else ${q(reviewerMembership)}::uuid end,
         'Seeded approval for the load run.'
    from app.review_envelopes e join app.candidate_versions v on v.id = e.candidate_id,
         (values ('it'), ('business')) r(role)
   where e.company_id = ${q(companyId)} and v.sequence in (${OLD_RELEASE_SEQ}, ${CURRENT_RELEASE_SEQ});
do $$
declare v record; r uuid; prev uuid;
begin
  set constraints all deferred;
  for v in select e.id as envelope_id, e.agent_id, c.sequence
             from app.review_envelopes e join app.candidate_versions c on c.id = e.candidate_id
            where e.company_id = ${q(companyId)} and c.sequence in (${OLD_RELEASE_SEQ}, ${CURRENT_RELEASE_SEQ})
            order by e.agent_id, c.sequence loop
    if v.sequence = ${OLD_RELEASE_SEQ} then prev := null; end if;
    r := gen_random_uuid();
    if prev is not null then
      update app.releases set superseded_by_release_id = r, superseded_at = clock_timestamp() where id = prev;
    end if;
    insert into app.releases
      (id, company_id, agent_id, candidate_id, envelope_id, target, gate_id, content_sha256, derived_sha256,
       installer_text_sha256, core_sha256, branch_sha256, judge_sha256, policy_id, policy_sha256,
       audience_group_ids, envelope_sha256, assembled_content, published_by_membership_id)
    select r, e.company_id, e.agent_id, e.candidate_id, e.id, e.target, e.gate_id, e.content_sha256,
           e.derived_sha256, e.installer_text_sha256, e.core_sha256, e.branch_sha256, e.judge_sha256,
           e.policy_id, e.policy_sha256, e.audience_group_ids, e.envelope_sha256,
           replace(c.content, app.installer_placeholder(), i.text), ${q(adminMembership)}
      from app.review_envelopes e
      join app.candidate_versions c on c.id = e.candidate_id
      join app.installer_texts i on i.gate_id = e.gate_id and i.target = e.target
     where e.id = v.envelope_id;
    prev := r;
  end loop;
  set constraints all immediate;
end $$;
drop table seed_audience;
select 'RELEASES|' || count(*) || '|' || count(*) filter (where superseded_by_release_id is null)
       || '|' || max(assembled_bytes) from app.releases where company_id = ${q(companyId)};`);

  /* The submitted candidate's envelopes and reviews: E4's worst review-queue page, per agent.
     Twenty envelopes is five groups by the four registered targets, which is how E4 built its own. */
  sqlScript(`
create temp table seed_agents as
  select id as agent_id, company_id, substring(name from '[0-9]+$')::int as agent_no
    from app.agents where company_id = ${q(companyId)};
insert into app.review_envelopes
  (company_id, agent_id, candidate_id, revision, content_sha256, derived_sha256, gate_id,
   gate_identity_sha256, target, installer_text_sha256, core_sha256, branch_sha256, judge_sha256,
   policy_id, policy_sha256, assembled_bytes, audience_group_ids, envelope_canonical, envelope_sha256,
   created_by_membership_id)
select v.company_id, v.agent_id, v.id,
       row_number() over (partition by v.id order by i.target, gr.name)::int,
       v.content_sha256, v.derived_sha256, i.gate_id, g.identity_sha256, i.target, i.text_sha256,
       i.core_sha256, i.branch_sha256, i.judge_sha256, p.id, p.sha256,
       app.assembled_bytes(v.content, i.text), array[gr.id],
       'e8-load-queue-' || v.id::text || '-' || i.target || '-' || gr.name,
       sha256(convert_to('e8-load-queue-' || v.id::text || '-' || i.target || '-' || gr.name, 'UTF8')),
       ${q(authorMembership)}
  from app.candidate_versions v
  join seed_agents a using (agent_id)
  join app.groups gr on gr.company_id = v.company_id
    and gr.name in (select format('%s-group-%s', ${q(slug)}, k) from generate_series(0, ${SHAPE.queueEnvelopes / 4 - 1}) k)
  join app.gate_identities g on g.active
  join app.installer_texts i on i.gate_id = g.id
  cross join app.release_policies p
 where v.company_id = ${q(companyId)} and p.active and v.sequence = ${SUBMITTED_SEQ};
insert into app.reviews (company_id, candidate_id, envelope_id, role, decision, reviewer_membership_id, reason)
  select e.company_id, e.candidate_id, e.id, 'it', 'approved', ${q(adminMembership)},
         'Seeded queue review for the load run.'
    from app.review_envelopes e join app.candidate_versions v on v.id = e.candidate_id
   where e.company_id = ${q(companyId)} and v.sequence = ${SUBMITTED_SEQ} and e.revision <= ${SHAPE.queueReviews};
select 'QUEUE|' || count(*) filter (where v.sequence = ${SUBMITTED_SEQ})
    || '|' || (select count(*) from app.candidate_versions where company_id = ${q(companyId)} and state = 'submitted')
  from app.review_envelopes e join app.candidate_versions v on v.id = e.candidate_id
 where e.company_id = ${q(companyId)};`);

  /* The ledger: one row per active member per current release, as E4's and E5's samples seeded. Then
     the two measured callers' own authorizations of the superseded releases of the first ten agents,
     so the catalog's "earlier" partition and its replacement read have rows to work on. */
  sqlScript(`
insert into app.release_downloads (company_id, release_id, membership_id, authorized_at)
  select r.company_id, r.id, m.id, clock_timestamp() - (row_number() over () || ' seconds')::interval
    from app.releases r
    join app.memberships m on m.company_id = r.company_id and m.status = 'active'
   where r.company_id = ${q(companyId)} and r.superseded_by_release_id is null;
insert into app.release_downloads (company_id, release_id, membership_id)
  select r.company_id, r.id, m.id
    from app.releases r
    join app.agents a on a.id = r.agent_id
    join (values (${q(adminMembership)}::uuid), (${q(reviewerMembership)}::uuid)) m(id) on true
   where r.company_id = ${q(companyId)} and r.superseded_by_release_id is not null
     and substring(a.name from '[0-9]+$')::int <= 10;
select 'LEDGER|' || count(*) from app.release_downloads where company_id = ${q(companyId)};`);

  /* The mix's download and release-read target: an EVEN agent, whose audience is all ten groups, so
     both measured callers are recipients of it. */
  const downloadRelease = one(`
select r.id::text from app.releases r join app.agents a on a.id = r.agent_id
 where r.company_id = ${q(companyId)} and r.superseded_by_release_id is null
   and substring(a.name from '[0-9]+$')::int = 2;`);
  if (!UUID_RE.test(downloadRelease)) throw new Error(`no download release for ${slug}: ${downloadRelease}`);
  const counts = one(
    `select (select count(*) from app.agents where company_id = ${q(companyId)})
        || '|' || (select count(*) from app.candidate_versions where company_id = ${q(companyId)})
        || '|' || (select count(*) from app.review_envelopes where company_id = ${q(companyId)})
        || '|' || (select count(*) from app.reviews where company_id = ${q(companyId)})
        || '|' || (select count(*) from app.releases where company_id = ${q(companyId)})
        || '|' || (select count(*) from app.release_downloads where company_id = ${q(companyId)})
        || '|' || (select count(*) from app.memberships where company_id = ${q(companyId)} and status = 'active')
        || '|' || (select max(assembled_bytes) from app.releases where company_id = ${q(companyId)});`,
  );
  const [agents, candidates, envelopes, reviews, releases, ledger, members, assembledBytes] = counts.split('|');
  return {
    index,
    slug,
    companyId,
    admin: { userId: adminUser, membershipId: adminMembership, email: `${slug}-admin@example.invalid` },
    reviewer: {
      userId: reviewerUser,
      membershipId: reviewerMembership,
      email: `${slug}-reviewer@example.invalid`,
    },
    author: { userId: authorUser, membershipId: authorMembership, email: `${slug}-author@example.invalid` },
    downloadRelease,
    counts: {
      agents: Number(agents),
      candidates: Number(candidates),
      envelopes: Number(envelopes),
      reviews: Number(reviews),
      releases: Number(releases),
      ledger: Number(ledger),
      activeMembers: Number(members),
      largestAssembledBytes: Number(assembledBytes),
    },
  };
}

/* ---------------------------------------------------------------- main */

function parseArgs(argv) {
  const a = { label: null, companies: ENVELOPE.companies, reseed: true };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--label') a.label = argv[++i];
    else if (argv[i] === '--companies') a.companies = Number.parseInt(argv[++i], 10);
    else if (argv[i] === '--no-reseed') a.reseed = false;
    else {
      process.stderr.write(`seed: unknown argument ${argv[i]}\n`);
      process.exit(2);
    }
  }
  if (a.label === null || !LABEL_RE.test(a.label)) {
    process.stderr.write('seed: --label matches ^[a-z0-9][a-z0-9-]{0,24}$ and decides every generated identity\n');
    process.exit(2);
  }
  if (!Number.isInteger(a.companies) || a.companies < 1) {
    process.stderr.write('seed: --companies is an integer of at least 1\n');
    process.exit(2);
  }
  return a;
}

export function worldPath(label) {
  return join(ROOT, '.scratch', 'e8', 'load', `world-${label}.json`);
}

