/* Second-factor calls to GoTrue (pages design 2.4, 2.6 and 4.1).

   Every call goes to GoTrue's public endpoints with the anon key and the caller's own access token as the bearer,
   obtained through accessTokenOf(session). GoTrue restricts every factor operation to that token's user, and the
   service key is never used here. Factors are a different GoTrue resource from sign-in, with their own error
   vocabulary, so this module sits beside lib/session.mjs rather than inside it and the verifier stays closed to factor
   changes (4.1; scenario B, a second factor type). The cost is this module's own small transport helper rather than a
   bearer-capable one opened up in the session module, which would widen what every importer of it could do.

   Results are { ok: true, ... } or { ok: false, code, gotrueStatus, gotrueErrorCode }, like the session helpers. code
   is a key of CODES in lib/errors.mjs, which this module does not reach; U5 checks every target. gotrueStatus and
   gotrueErrorCode exist for the route's log line: GoTrue's error_code is a fixed vocabulary (O9) and is kept only when
   it has that vocabulary's shape. No TOTP secret, QR code, otpauth URI, challenge id or six-digit code is logged or
   kept anywhere; the secret passes through one enrolment answer.

   Enrolment is one POST /factors and no deletion of any kind (2.4, R-M1). GoTrue's own cleanup runs at every enrolment
   and removes unverified factors that are old and have no challenge, in one conditional statement; a deletion issued
   here instead would race a verification in another tab and could destroy a factor that had just become verified,
   because GoTrue offers no conditional delete (O22). The friendly name carries the UTC time and six random hex
   characters, so two enrolments in one second do not collide; mfa_factor_name_conflict is retried once with a fresh
   suffix and then answers E_MFA_UNAVAILABLE. The answer must pass the shape check of 2.4 before any of it reaches a
   browser. A factor GoTrue created whose answer fails that check stays unverified and without a challenge, which is the
   class GoTrue's own cleanup collects.

   Verification is challenge then verify inside one request, because GoTrue refuses a verification from an address
   other than the challenge's (O4); the challenge id never leaves the server. A code that is not exactly six digits is
   refused before any GoTrue call. The per-account bound on failed verifications is GoTrue's hook (2.8) where the hook
   is installed, and, since migration 012 (HB-F2), the route's own bound in lib/services/factor-bound.mjs, which this
   module does not hold: it reports what GoTrue judged (`judged`, below), and the route settles the bound with it. The
   hook's refusal arrives as a 429 whose error_code GoTrue v2.192.0 writes as unknown (observed on the local stack,
   evidence/pages-server.md), so after the table misses, the verification path maps a 429 to E_RATE_LIMITED and any
   other refusal to E_MFA_UNAVAILABLE, the retryable answer for a hook that failed.

   Removal is one DELETE of the factor the person named. GoTrue offers no conditional delete (O22): a factor another tab
   verified between the page's render and the press is deleted too when this session is aal2. The page discloses that;
   nothing here deletes a factor nobody named. */

import { randomBytes } from 'node:crypto';

import { accessTokenOf } from '../session.mjs';

/* 2.4's resource guard on the QR code, far above the provider's own output: a bound on what is passed to a browser, not
   a format test. The enrolment answer is read under this bound plus room for its other fields, so narrowing the guard
   is this one constant. */
export const QR_CODE_MAX_BYTES = 1024 * 1024;
const ANSWER_MAX_BYTES = QR_CODE_MAX_BYTES + 64 * 1024;

/* The pinned SVGo serializer's opening (O14): the XML prologue, the generator comment, then the svg element. */
export const QR_PROLOGUE = '<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n<svg';
const TOTP_URI_PREFIX = 'otpauth://totp/';
const TOTP_SECRET = /^[A-Z2-7]{16,128}=*$/;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const SIX_DIGITS = /^[0-9]{6}$/;
const SUPPORTED_FACTOR_TYPES = Object.freeze(['totp']);
const MIDDLE_DOT = String.fromCharCode(0xb7);

/* GoTrue error_code (legacy body shape, no API version header, as lib/session.mjs sends) to the application code. */
export const GOTRUE_ERROR_CODES = Object.freeze({
  mfa_verification_failed: 'E_MFA_CODE_INVALID',
  insufficient_aal: 'E_MFA_STEP_UP_REQUIRED',
  too_many_enrolled_mfa_factors: 'E_MFA_FACTOR_LIMIT',
  mfa_factor_not_found: 'E_NOT_FOUND',
  mfa_totp_enroll_not_enabled: 'E_MFA_NOT_ENABLED',
  mfa_totp_verify_not_enabled: 'E_MFA_NOT_ENABLED',
  mfa_ip_address_mismatch: 'E_MFA_UNAVAILABLE',
  mfa_challenge_expired: 'E_MFA_UNAVAILABLE',
  mfa_factor_name_conflict: 'E_MFA_UNAVAILABLE',
  over_request_rate_limit: 'E_RATE_LIMITED',
  session_not_found: 'E_UNAUTHENTICATED',
});

function env(name) {
  const v = process.env[name];
  if (typeof v !== 'string' || v.length === 0) throw new Error(`E_CONFIG ${name}`);
  return v;
}

/* The body as JSON when it parses and stays within ANSWER_MAX_BYTES; over marks an answer cut off at the bound. */
async function readAnswer(response) {
  const reader = response.body?.getReader?.();
  if (!reader) return { json: null, over: false };
  const chunks = [];
  let size = 0;
  try {
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      size += value.byteLength;
      if (size > ANSWER_MAX_BYTES) {
        reader.cancel().catch(() => {});
        return { json: null, over: true };
      }
      chunks.push(value);
    }
  } catch {
    return { json: null, over: false };
  }
  try {
    return { json: JSON.parse(Buffer.concat(chunks).toString('utf8')), over: false };
  } catch {
    return { json: null, over: false };
  }
}

/* One GoTrue call with the caller's bearer: { status, json, over }, status null when the fetch itself failed. */
async function gotrue(session, method, path, body) {
  const headers = {
    apikey: env('SUPABASE_ANON_KEY'),
    authorization: `Bearer ${accessTokenOf(session)}`,
    accept: 'application/json',
  };
  if (body !== undefined) headers['content-type'] = 'application/json';
  let response;
  try {
    response = await fetch(`${env('SUPABASE_URL')}/auth/v1${path}`, {
      method,
      headers,
      body: body === undefined ? undefined : JSON.stringify(body),
    });
  } catch {
    return { status: null, json: null, over: false };
  }
  return { status: response.status, ...(await readAnswer(response)) };
}

const succeeded = (answer) => answer.status !== null && answer.status >= 200 && answer.status < 300 && !answer.over;

/* The error_code that reaches a log line is a key of the table above or the fixed word `unknown`; a string GoTrue
   answered that the table does not name is never copied, whatever its shape, because a shape check admits any
   1-to-64-character token and the log is the one place an upstream body could otherwise reach (E7M-C-F5; E7
   design 1.5's closed log vocabulary). null when the answer carried no string at all. */
const refused = (code, answer) => ({
  ok: false,
  code,
  gotrueStatus: answer?.status ?? null,
  gotrueErrorCode:
    typeof answer?.json?.error_code === 'string'
      ? Object.hasOwn(GOTRUE_ERROR_CODES, answer.json.error_code)
        ? answer.json.error_code
        : 'unknown'
      : null,
});

/* 2.6: the error_code table first; after it misses, on the verification path a 429 is E_RATE_LIMITED and anything else
   E_MFA_UNAVAILABLE; on the other paths an unmapped 4xx is E_INTERNAL, and a thrown fetch, a 5xx, an answer over the
   bound or any other status is E_MFA_UNAVAILABLE. A 2xx whose body fails a shape check is answered by its caller. */
function refusal(answer, { verification = false } = {}) {
  const errorCode = answer.json?.error_code;
  if (typeof errorCode === 'string' && Object.hasOwn(GOTRUE_ERROR_CODES, errorCode))
    return refused(GOTRUE_ERROR_CODES[errorCode], answer);
  if (answer.status === null || answer.over) return refused('E_MFA_UNAVAILABLE', answer);
  if (verification) return refused(answer.status === 429 ? 'E_RATE_LIMITED' : 'E_MFA_UNAVAILABLE', answer);
  return refused(answer.status >= 400 && answer.status < 500 ? 'E_INTERNAL' : 'E_MFA_UNAVAILABLE', answer);
}

/**
 * listFactors(session) -> { ok: true, factors: [{ factorId, type, status, friendlyName, createdAt }] } | refusal
 * GET /auth/v1/user, keeping each factor of a supported type (TOTP only in this slice), verified and unverified alike.
 * GoTrue leaves the factors key out for a user who has none.
 */
export async function listFactors(session) {
  const answer = await gotrue(session, 'GET', '/user');
  if (!succeeded(answer)) return refusal(answer);
  const user = answer.json;
  const factors = user?.factors ?? [];
  if (typeof user !== 'object' || user === null || !Array.isArray(factors)) return refused('E_MFA_UNAVAILABLE', answer);
  const out = [];
  for (const f of factors) {
    if (!SUPPORTED_FACTOR_TYPES.includes(f?.factor_type)) continue;
    if (
      typeof f.id !== 'string' ||
      !UUID.test(f.id) ||
      (f.status !== 'verified' && f.status !== 'unverified') ||
      typeof f.friendly_name !== 'string' ||
      typeof f.created_at !== 'string'
    )
      return refused('E_MFA_UNAVAILABLE', answer);
    out.push({
      factorId: f.id.toLowerCase(),
      type: f.factor_type,
      status: f.status,
      friendlyName: f.friendly_name,
      createdAt: f.created_at,
    });
  }
  return { ok: true, factors: out };
}

function friendlyName() {
  const now = new Date().toISOString();
  return `Authenticator app, ${now.slice(0, 10)} ${now.slice(11, 19)} UTC ${MIDDLE_DOT} ${randomBytes(3).toString('hex')}`;
}

/* 2.4's shape check, on GoTrue's field names, before the answer is flattened for the browser. */
function enrolmentOf(answer) {
  const { id, totp } = answer.json ?? {};
  const qr = totp?.qr_code;
  if (
    typeof id !== 'string' ||
    !UUID.test(id) ||
    typeof qr !== 'string' ||
    !qr.startsWith(QR_PROLOGUE) ||
    !qr.trimEnd().endsWith('</svg>') ||
    Buffer.byteLength(qr, 'utf8') > QR_CODE_MAX_BYTES ||
    typeof totp.uri !== 'string' ||
    !totp.uri.startsWith(TOTP_URI_PREFIX) ||
    typeof totp.secret !== 'string' ||
    !TOTP_SECRET.test(totp.secret)
  )
    return refused('E_MFA_UNAVAILABLE', answer);
  return { ok: true, factorId: id.toLowerCase(), qrCodeSvg: qr, uri: totp.uri, secret: totp.secret };
}

/**
 * enrollTotp(session) -> { ok: true, factorId, qrCodeSvg, uri, secret } | refusal
 * One POST /auth/v1/factors with no issuer (GoTrue names the host of its site_url), retried once on a name conflict.
 */
export async function enrollTotp(session) {
  let answer = await gotrue(session, 'POST', '/factors', { factor_type: 'totp', friendly_name: friendlyName() });
  if (!succeeded(answer) && answer.json?.error_code === 'mfa_factor_name_conflict')
    answer = await gotrue(session, 'POST', '/factors', { factor_type: 'totp', friendly_name: friendlyName() });
  return succeeded(answer) ? enrolmentOf(answer) : refusal(answer);
}

/* HB-F2's closed rule (evidence/ena7-end1-hbf2.md section 5, D8, after the design critique's HB-C1). A verify answer
   GoTrue gives BEFORE it checks the code judged nothing: its per-address 429, and these error codes. Every other
   answer at the verify stage, a 5xx, an unknown or absent error_code, an unreadable or over-bound body, a failed fetch,
   a 2xx without tokens, may follow a judged code and counts as a wrong one, so no guess is refunded on an answer that
   could have spent it; a GoTrue upgrade that renamed the wrong-code error would then lock sooner, never later. */
const DECIDED_BEFORE_THE_CODE = new Set([
  'mfa_ip_address_mismatch',
  'mfa_challenge_expired',
  'mfa_factor_not_found',
  'session_not_found',
  'mfa_totp_verify_not_enabled',
]);
/** isTotpCode(code): exactly six digits, the shape verifyTotp refuses before any GoTrue call. The route asks it before
    the bound's begin, so a malformed code spends nothing of the account's budget (HB-F2, D7). */
export const isTotpCode = (code) => typeof code === 'string' && SIX_DIGITS.test(code);

const judgedAtVerify = (answer) =>
  answer.status === 429 ||
  (typeof answer.json?.error_code === 'string' && DECIDED_BEFORE_THE_CODE.has(answer.json.error_code))
    ? 'undecided'
    : 'invalid';

/**
 * verifyTotp(session, factorId, totpCode) -> { ok: true, tokens: { accessToken, refreshToken, expiresIn }, judged } | refusal & { judged }
 * Challenge then verify, one request. The tokens are GoTrue's answer for the same session, now at aal2 (O5); the route
 * hands them to sessionCookies, and the next request's verifySession reads aal from the new access token.
 * `judged` is what the route's bound records (HB-F2): `valid`; `invalid`; or `undecided`, for everything before the
 * verify request is sent and for a verify answer GoTrue gives before it checks the code (DECIDED_BEFORE_THE_CODE).
 */
export async function verifyTotp(session, factorId, totpCode) {
  if (typeof factorId !== 'string' || !UUID.test(factorId)) return { ...refused('E_NOT_FOUND'), judged: 'undecided' };
  if (typeof totpCode !== 'string' || !SIX_DIGITS.test(totpCode))
    return { ...refused('E_MFA_CODE_INVALID'), judged: 'undecided' };
  const challenge = await gotrue(session, 'POST', `/factors/${factorId}/challenge`, {});
  if (!succeeded(challenge)) return { ...refusal(challenge, { verification: true }), judged: 'undecided' };
  const challengeId = challenge.json?.id;
  if (typeof challengeId !== 'string' || !UUID.test(challengeId))
    return { ...refused('E_MFA_UNAVAILABLE', challenge), judged: 'undecided' };
  const verified = await gotrue(session, 'POST', `/factors/${factorId}/verify`, {
    challenge_id: challengeId,
    code: totpCode,
  });
  if (!succeeded(verified)) return { ...refusal(verified, { verification: true }), judged: judgedAtVerify(verified) };
  const { access_token: accessToken, refresh_token: refreshToken, expires_in: expiresIn } = verified.json ?? {};
  if (typeof accessToken !== 'string' || typeof refreshToken !== 'string')
    return { ...refused('E_MFA_UNAVAILABLE', verified), judged: 'invalid' };
  return { ok: true, tokens: { accessToken, refreshToken, expiresIn }, judged: 'valid' };
}

/**
 * removeFactor(session, factorId) -> { ok: true } | refusal
 * One DELETE /auth/v1/factors/{factorId}. GoTrue refuses a verified factor below aal2 with insufficient_aal.
 */
export async function removeFactor(session, factorId) {
  if (typeof factorId !== 'string' || !UUID.test(factorId)) return refused('E_NOT_FOUND');
  const answer = await gotrue(session, 'DELETE', `/factors/${factorId}`);
  return succeeded(answer) ? { ok: true } : refusal(answer);
}
